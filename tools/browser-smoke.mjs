import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const browser=await chromium.launch({headless:true});
fs.mkdirSync('test-results',{recursive:true});
for(const [label,width,height] of [['desktop',1440,1000],['mobile',390,844],['compact',320,740]]) {
 const page=await browser.newPage({viewport:{width,height}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8080',{waitUntil:'networkidle'});
 assert.equal(await page.locator('h1').count(),1);
 assert.equal(await page.locator('main section').count(),11);
 assert.equal(await page.locator('details').count(),8);
 const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(overflow.scroll<=overflow.width,`${label}: overflow ${JSON.stringify(overflow)}`);
 const ctas=await page.locator('[data-atos-cta]').all();
 assert.ok(ctas.length>=5);
 for(const cta of ctas) assert.ok((await cta.getAttribute('href')).startsWith('https://wa.me/5511957314749?text='));
 const firstFaq=page.locator('details').first();
 await firstFaq.locator('summary').click();
 assert.ok(await firstFaq.getAttribute('open')!==null,'FAQ não abriu');
 await firstFaq.locator('summary').focus();
 await page.keyboard.press('Enter');
 assert.equal(await firstFaq.getAttribute('open'),null,'FAQ não fechou com teclado');
 assert.equal(await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||i.naturalWidth===0).length),0,'Imagem quebrada');
 await page.screenshot({path:`test-results/atos-${label}.png`,fullPage:true});
 assert.deepEqual(errors,[]);
 await page.close();
}
const editor=await browser.newPage();
await editor.goto('http://127.0.0.1:8080/wp-login.php');
await editor.locator('#user_login').fill('atos-test');
await editor.locator('#user_pass').fill('Local-test-only-1234!');
await editor.locator('#wp-submit').click();
await editor.waitForURL('**/wp-admin/**');
await editor.goto('http://127.0.0.1:8080/wp-admin/post-new.php');
await editor.waitForFunction(()=>window.wp?.blocks?.getBlockType('core/details'),{timeout:30000});
const invalid=await editor.evaluate(source=>{
 const collect=blocks=>blocks.flatMap(b=>[...(b.isValid===false?[{name:b.name,html:b.originalContent?.slice(0,200)}]:[]),...collect(b.innerBlocks||[])]);
 return collect(window.wp.blocks.parse(source));
},fs.readFileSync('theme/templates/front-page.html','utf8'));
assert.deepEqual(invalid,[],'Blocos inválidos para edição visual: '+JSON.stringify(invalid));
await editor.close();
await browser.close();
console.log('OK: computador, celular 390px e 320px, WhatsApp, FAQ, teclado, imagens e edição visual.');
